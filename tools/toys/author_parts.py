# Validate all grids are exactly 16x16
for name, grid in PARTS.items():
    lines = grid.splitlines()
    assert len(lines) == 16, f"{name}: expected 16 lines, got {len(lines)}"
    for row_idx, line in enumerate(lines):
        assert len(line) == 16, f"{name} row {row_idx}: expected 16 chars, got {len(line)}: '{line}'"
    (PARTS_DIR / f"{name}.txt").write_text(grid, encoding="utf-8")

print(f"Successfully authored all {len(PARTS)} part icons into {PARTS_DIR}!")
