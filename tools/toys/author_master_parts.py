# Validation and write to disk
for name, grid in MASTER_PARTS.items():
    lines = grid.splitlines()
    assert len(lines) == 16, f"{name}: expected 16 lines, got {len(lines)}"
    for r, l in enumerate(lines):
        assert len(l) == 16, f"{name} r{r}: expected 16 chars, got {len(l)} ('{l}')"
    (PARTS_DIR / f"{name}.txt").write_text(grid, encoding="utf-8")

print(f"Successfully wrote all {len(MASTER_PARTS)} master pixel art parts into {PARTS_DIR}!")
