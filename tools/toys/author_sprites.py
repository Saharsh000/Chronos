def dump_all_sources() -> None:
    """Save all authored source grids as text files in tools/toys/src/."""
    for category, items in [
        ("bodies", BODIES),
        ("movers", MOVERS),
        ("cores", CORES),
        ("overrides", OVERRIDES),
        ("parts", PARTS),
    ]:
        cdir = SRC_DIR / category
        cdir.mkdir(parents=True, exist_ok=True)
        for name, grid in items.items():
            fpath = cdir / f"{name}.txt"
            fpath.write_text(grid.strip() + "\n", encoding="utf-8")


if __name__ == "__main__":
    dump_all_sources()
    print(f"Dumped all V2 source text grids into {SRC_DIR}")
